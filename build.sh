#!/bin/sh
# Builds everything from src/:
#   LOONFIRE_SERVER=wss://… (or EMBERWIND_SERVER) bakes the online server into the page (for GitHub Pages etc.)
#   SITE_URL=https://…         the public address (default https://playloonfire.github.io)
#   out/site/               what GitHub Pages publishes (game + web/ assets)
#   out/index.html          the game (single file)            TEST=1 adds automation hooks
#   server/sim.js           the shared simulation, as a Node factory for the game server
#   server/public/index.html  the page the game server hosts
cd "$(dirname "$0")"
OUT=${OUT:-out/index.html}
mkdir -p out server/public
{
  awk '/__FONTS__/{ system("cat src/fonts.css"); next } { print }' src/head.html
  echo '<script>'
  echo '(function(){'
  echo '"use strict";'
  for f in src/0*.js src/1*.js; do echo "// ---- $(basename $f) ----"; cat "$f"; echo; done
  if [ "$TEST" = "1" ]; then cat src/99-test.js; fi
  echo '})();'
  echo '</script>'
  echo '</body>'
  echo '</html>'
} > "$OUT"
# LOONFIRE_SERVER=wss://your-server.example.com ./build.sh  → the page connects there with zero setup
GAME_SERVER=${LOONFIRE_SERVER:-$EMBERWIND_SERVER}
if [ -n "$GAME_SERVER" ]; then
  sed -i.bak "s#__EMBERWIND_SERVER__#$GAME_SERVER#" "$OUT" && rm -f "$OUT.bak"
fi
# SITE_URL is the public address search engines should treat as the real one
SITE_URL=${SITE_URL:-https://playloonfire.github.io}
SITE_URL=${SITE_URL%/}
sed -i.bak "s#__SITE_URL__#$SITE_URL#g" "$OUT" && rm -f "$OUT.bak"
# out/site = everything GitHub Pages publishes (game + icons, preview image, sitemap…)
rm -rf out/site && mkdir -p out/site && cp "$OUT" out/site/index.html && cp -R web/. out/site/
for f in out/site/robots.txt out/site/sitemap.xml out/site/site.webmanifest; do
  sed -i.bak -e "s#__SITE_URL__#$SITE_URL#g" -e "s#__DATE__#$(date -u +%Y-%m-%d)#g" "$f" && rm -f "$f.bak"
done
touch out/site/.nojekyll
{
  echo '// GENERATED by build.sh from ../src — edit the sources, not this file.'
  echo '"use strict";'
  echo 'module.exports = function createSim(){'
  for f in src/01-core.js src/03-world.js src/04-entities.js src/04b-sim.js src/04c-codec.js src/05-ai.js src/srv-glue.js; do echo "// ---- $(basename $f) ----"; cat "$f"; echo; done
  echo '};'
} > server/sim.js
cp -R out/site/. server/public/
wc -l "$OUT" server/sim.js | head -2
